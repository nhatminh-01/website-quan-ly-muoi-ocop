    (criteria_set_id, parent_id, code, title, item_type, section_code,
     max_score, requirement_text, sort_order, active)
SELECT sets.id, NULL, sections.code, sections.title, 'section', sections.code,
       sections.max_score, '', sections.sort_order, TRUE
FROM app.ocop_criteria_sets AS sets
CROSS JOIN (VALUES
    ('A', 'Sản phẩm và sức mạnh của cộng đồng', 40, 10),
    ('B', 'Khả năng tiếp thị', 25, 20),
    ('C', 'Chất lượng sản phẩm', 35, 30)
) AS sections(code, title, max_score, sort_order)
WHERE sets.code LIKE 'QD26-%'
ON CONFLICT (criteria_set_id, code) DO NOTHING;

DO $$
DECLARE
    invalid_sets INTEGER;
    invalid_sections INTEGER;
BEGIN
    SELECT count(*) INTO invalid_sets
    FROM app.ocop_criteria_sets
    WHERE code LIKE 'QD26-%'
      AND (legal_document <> '26/2026/QĐ-TTg' OR version <> '2026.1'
           OR effective_from <> DATE '2026-05-22' OR max_score <> 100 OR NOT active);

    SELECT count(*) INTO invalid_sections
    FROM app.ocop_criteria AS criteria
    JOIN app.ocop_criteria_sets AS sets ON sets.id = criteria.criteria_set_id
    WHERE sets.code LIKE 'QD26-%' AND criteria.code IN ('A', 'B', 'C')
      AND (criteria.item_type <> 'section' OR NOT criteria.active);

    IF (SELECT count(*) FROM app.ocop_criteria_sets WHERE code LIKE 'QD26-%') <> 26
       OR invalid_sets <> 0
       OR (SELECT count(*) FROM app.ocop_criteria AS criteria
           JOIN app.ocop_criteria_sets AS sets ON sets.id = criteria.criteria_set_id
           WHERE sets.code LIKE 'QD26-%' AND criteria.code IN ('A', 'B', 'C')) <> 78
       OR invalid_sections <> 0 THEN
        RAISE EXCEPTION 'Danh mục OCOP QD26 hiện có không khớp migration chuẩn.';
    END IF;
END $$;

