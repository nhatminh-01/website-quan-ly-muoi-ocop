    ON app.ocop_criteria_sets(active, sort_order);
CREATE INDEX IF NOT EXISTS IX_OCOP_CriteriaSetClass
    ON app.ocop_criteria_sets(product_category, product_group, active);
CREATE INDEX IF NOT EXISTS IX_OCOP_CriteriaTree
    ON app.ocop_criteria(criteria_set_id, parent_id, sort_order, id);
CREATE INDEX IF NOT EXISTS IX_OCOP_CriteriaOptions
    ON app.ocop_criteria_options(criterion_id, sort_order, id);
CREATE INDEX IF NOT EXISTS IX_OCOP_ProductCriteriaSet
    ON app.ocop_products(criteria_set_id, status, id);
CREATE INDEX IF NOT EXISTS IX_OCOP_ApplicationCriteriaSet
    ON app.ocop_applications(criteria_set_id, status, id);

