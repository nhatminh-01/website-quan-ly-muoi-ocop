ALTER TABLE app.ocop_applications
    ADD COLUMN IF NOT EXISTS criteria_set_id INTEGER REFERENCES app.ocop_criteria_sets(id);

CREATE UNIQUE INDEX IF NOT EXISTS UX_OCOP_CriteriaSetSort
