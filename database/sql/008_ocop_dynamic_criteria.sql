CREATE TABLE IF NOT EXISTS app.ocop_criteria_sets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    product_category VARCHAR(150) NOT NULL,
    product_group VARCHAR(150) NOT NULL,
    product_subgroup VARCHAR(255) NOT NULL DEFAULT '',
    legal_document VARCHAR(100) NOT NULL,
    version VARCHAR(50) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    max_score NUMERIC NOT NULL DEFAULT 100 CHECK (max_score > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL CHECK (sort_order > 0),
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS app.ocop_criteria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criteria_set_id INTEGER NOT NULL REFERENCES app.ocop_criteria_sets(id),
    parent_id INTEGER REFERENCES app.ocop_criteria(id),
    code VARCHAR(50) NOT NULL,
    title VARCHAR(500) NOT NULL,
    item_type VARCHAR(20) NOT NULL
        CHECK (item_type IN ('section', 'group', 'criterion', 'note')),
    section_code VARCHAR(1) CHECK (section_code IS NULL OR section_code IN ('A', 'B', 'C')),
    max_score NUMERIC CHECK (max_score IS NULL OR max_score >= 0),
    requirement_text TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (criteria_set_id, code)
);

CREATE TABLE IF NOT EXISTS app.ocop_criteria_options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_id INTEGER NOT NULL REFERENCES app.ocop_criteria(id),
    label VARCHAR(2000) NOT NULL,
    score NUMERIC NOT NULL CHECK (score >= 0),
    min_star INTEGER CHECK (min_star IS NULL OR min_star IN (3, 4, 5)),
    is_eliminating BOOLEAN NOT NULL DEFAULT FALSE,
    evidence_hint TEXT NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

